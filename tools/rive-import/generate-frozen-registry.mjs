import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const toolDirectory = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = resolve(toolDirectory, '..', '..');
const sourceRoot = resolve(process.argv[2] ?? '');

if (!process.argv[2]) {
  throw new Error('Usage: node tools/rive-import/generate-frozen-registry.mjs <frozen-rive-runtime-root>');
}

const censusPath = join(repositoryRoot, 'docs', 'for-ai', 'rive-hya', 'runtime-census.json');
const outputPath = join(repositoryRoot, 'animation-spec', 'src', 'rive', 'import', 'generated', 'frozen-registry.ts');
const census = JSON.parse(await readFile(censusPath, 'utf8'));

async function collectHeaders(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await collectHeaders(path));
    else if (entry.name.endsWith('_base.hpp')) files.push(path);
  }
  return files;
}

const generatedRoot = join(sourceRoot, 'include', 'rive', 'generated');
const registrySource = await readFile(join(sourceRoot, census.source.registry), 'utf8');
const definitions = new Map();
for (const path of await collectHeaders(generatedRoot)) {
  const source = await readFile(path, 'utf8');
  const classMatch = source.match(/class\s+(\w+)Base\s*:\s*public\s+(\w+)/);
  if (!classMatch) continue;
  const [, name, parent] = classMatch;
  const propertyTypes = new Map();
  let currentProperty;
  for (const line of source.split(/\r?\n/)) {
    const caseMatch = line.match(/case\s+(\w+)PropertyKey:/);
    if (caseMatch) currentProperty = caseMatch[1];
    const typeMatch = line.match(/Core(Uint|Int|Bool|String|Bytes|Double|Color)Type::deserialize\(reader\)/);
    if (currentProperty && typeMatch) {
      propertyTypes.set(currentProperty, typeMatch[1].toLowerCase());
      currentProperty = undefined;
    }
  }
  definitions.set(name, { parent, propertyTypes });
}

const registryWireKinds = new Map();
let pendingRegistryProperties = [];
// Generated CoreRegistry occasionally wraps after `Base::`. Normalizing only
// that token boundary keeps the line-oriented wire-kind scan deterministic
// while ensuring wrapped and unwrapped case labels have identical meaning.
const normalizedRegistrySource = registrySource.replace(/::\s+/g, '::');
for (const line of normalizedRegistrySource.split(/\r?\n/)) {
  const caseMatch = line.match(/case\s+(\w+)Base::(\w+)PropertyKey:/);
  if (caseMatch) pendingRegistryProperties.push(`${caseMatch[1]}.${caseMatch[2]}`);
  const returnMatch = line.match(/return\s+Core(Uint|Int|Bool|String|Bytes|Double|Color)Type::id;/);
  if (returnMatch) {
    const wireKind = returnMatch[1].toLowerCase();
    for (const property of pendingRegistryProperties) registryWireKinds.set(property, wireKind);
    pendingRegistryProperties = [];
  }
}

function lineageFor(name) {
  const lineage = [];
  const seen = new Set();
  let current = name;
  while (current && current !== 'Core') {
    if (seen.has(current)) throw new Error(`Inheritance cycle at ${name}: ${current}`);
    seen.add(current);
    lineage.push(current);
    current = definitions.get(current)?.parent;
  }
  lineage.push('Core');
  return lineage;
}

const properties = census.properties.map(property => {
  const definition = definitions.get(property.owner);
  const wireKind = definition?.propertyTypes.get(property.name) ??
    registryWireKinds.get(`${property.owner}.${property.name}`);
  if (!wireKind) {
    throw new Error(`No wire kind for ${property.owner}.${property.name} (${property.key})`);
  }
  return [property.key, property.name, property.owner, wireKind, definition?.propertyTypes.has(property.name) ?? false, property.family, property.goal];
});

const objects = census.objects.map(object => [
  object.typeKey,
  object.name,
  object.family,
  object.goal,
  lineageFor(object.name),
]);

if (objects.length !== census.totals.objectTypes || properties.length !== census.totals.propertyKeys) {
  throw new Error('Generated registry count does not match frozen census.');
}

const licenseSource = await readFile(join(sourceRoot, 'LICENSE'), 'utf8');
const sha256 = value => createHash('sha256').update(value).digest('hex');
const banner = `// Generated by tools/rive-import/generate-frozen-registry.mjs. Do not edit.\n`;
const output = `${banner}
export type FrozenWireKind = 'uint' | 'int' | 'bool' | 'string' | 'bytes' | 'double' | 'color';

export interface FrozenObjectRecord {
  readonly typeKey: number;
  readonly name: string;
  readonly family: string;
  readonly goal: string;
  readonly lineage: readonly string[];
}

export interface FrozenPropertyRecord {
  readonly key: number;
  readonly name: string;
  readonly owner: string;
  readonly wireKind: FrozenWireKind;
  readonly serialized: boolean;
  readonly family: string;
  readonly goal: string;
}

export const FROZEN_REGISTRY_IDENTITY = Object.freeze(${JSON.stringify({
  compatibilityTupleId: census.compatibilityTupleId,
  publicCommit: census.source.publicCommit,
  riveHead: census.source.riveHead,
  censusInputDigestSha256: census.source.inputDigestSha256,
  coreRegistrySha256: sha256(registrySource),
  license: 'MIT',
  licenseSha256: sha256(licenseSource),
  generatorInput: relative(repositoryRoot, censusPath).replaceAll('\\', '/'),
}, null, 2)} as const);

const OBJECT_ROWS = ${JSON.stringify(objects)} as const;
const PROPERTY_ROWS = ${JSON.stringify(properties)} as const;

export const FROZEN_OBJECTS: readonly FrozenObjectRecord[] = Object.freeze(
  OBJECT_ROWS.map(([typeKey, name, family, goal, lineage]) => Object.freeze({
    typeKey,
    name,
    family,
    goal,
    lineage: Object.freeze([...lineage]),
  })),
);

export const FROZEN_PROPERTIES: readonly FrozenPropertyRecord[] = Object.freeze(
  PROPERTY_ROWS.map(([key, name, owner, wireKind, serialized, family, goal]) => Object.freeze({
    key,
    name,
    owner,
    wireKind,
    serialized,
    family,
    goal,
  })),
);
`;

await writeFile(outputPath, output, 'utf8');
console.log(`generated ${relative(repositoryRoot, outputPath)}: objects=${objects.length} properties=${properties.length}`);
