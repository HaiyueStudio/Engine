import test from 'node:test';
import assert from 'node:assert/strict';
import { GuiBatch, GuiShapeRenderer, GuiTextBatch, buildBitmapFont } from '../dist/experimental.js';
import { createAuditGpuDevice, getAuditGpuDeviceState } from '../../scripts/benchmark/real-renderer-audit-device.mjs';
const shape = () => ({ x: 0, y: 0, width: 80, height: 40, radius: 8, strokeWidth: 1, color: [1, 1, 1, 1], clip: { x: 0, y: 0, width: 100, height: 100 } });
test('unchanged shapes survive neighbouring text rebuild, mutations and release invalidate retained geometry', () => {
  const batch = new GuiBatch(), command = shape();
  const rebuild = () => { batch.clear(); batch.addShape(command); batch.rebuild(); };
  rebuild(); const version = batch.version, vertices = batch.vertexData.slice();
  for (let n = 0; n < 100; n++) rebuild();
  assert.equal(batch.version, version); assert.deepEqual(batch.vertexData, vertices);
  command.clip.width = 50; rebuild(); assert.equal(batch.version, version + 1);
  command.color[3] = 0.5; rebuild(); assert.equal(batch.version, version + 2);
  batch.clear({ releaseVertexData: true }); batch.addShape(command); batch.rebuild();
  assert.equal(batch.vertexCount, 216); assert.ok(batch.vertexData.length > 0);
  batch.clear(); batch.rebuild(); assert.equal(batch.vertexCount, 0);
});
test('viewport uploads only on size change or renderer recreation, draws remain identical', () => {
  const device = createAuditGpuDevice(), audit = getAuditGpuDeviceState(device);
  const engine = { device, format: 'bgra8unorm', displayWidth: 320, displayHeight: 180, getDepthFormat: () => 'depth24plus' };
  const renderer = new GuiShapeRenderer(), batch = new GuiBatch();
  batch.addShape(shape()); batch.rebuild(); renderer.prepare(engine);
  const pass = device.createCommandEncoder().beginRenderPass({ colorAttachments: [] });
  renderer.render(pass, batch); const initial = audit.snapshot().uploads.calls;
  for (let i = 0; i < 100; i++) renderer.render(pass, batch);
  assert.equal(audit.snapshot().uploads.calls, initial);
  engine.displayWidth = 640; renderer.render(pass, batch);
  assert.equal(audit.snapshot().uploads.calls, initial + 1);
  renderer.destroy(); renderer.prepare(engine); renderer.render(pass, batch);
  assert.equal(audit.snapshot().uploads.calls, initial + 3);
  renderer.destroy(); assert.equal(audit.snapshot().resources.buffer.live, 0);
});
test('text lays out once, skips identical uploads and respects mutable font metrics', () => {
  const font = buildBitmapFont({ chars: 'ABC?', fontSize: 10, atlasSize: 64, canvasFactory: (width, height) => ({ width, height, getContext: () => ({ measureText: () => ({ width: 8, actualBoundingBoxAscent: 8, actualBoundingBoxDescent: 2 }), clearRect() {}, fillText() {} }) }) }).data;
  const command = { text: 'AB', x: 0, y: 0, width: 20, height: 30, fontSize: 10, multiline: true, wrap: true, color: [1, 1, 1, 1] };
  const batch = new GuiTextBatch();
  const rebuild = () => { batch.clear(); batch.addText(command); batch.rebuild(font); };
  rebuild(); const version = batch.version;
  let reads = 0; const get = font.chars.get.bind(font.chars); font.chars.get = (...args) => { reads++; return get(...args); };
  for (let n = 0; n < 100; n++) rebuild();
  assert.equal(reads, 200); assert.equal(batch.version, version);
  font.chars.get(65).xadvance += 2;
  rebuild(); assert.ok(batch.version > version);
  command.text = 'ABC'; command.color[0] = 0.5; rebuild(); assert.ok(reads > 0);
  const fresh = new GuiTextBatch(); fresh.addText(command); fresh.rebuild(font);
  assert.equal(batch.vertexCount, fresh.vertexCount);
  assert.deepEqual(batch.vertexData, fresh.vertexData);
  batch.clear(); batch.rebuild(font); assert.equal(batch.vertexCount, 0);
});
