import { readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { createPrecompiledShaderArtifactV2 } from '../dist/index.js';
import { compileDeferredLightingArtifact, loadPrivateBuildModule } from './generate-deferred-lighting-production.mjs';
import { compactArtifactLiteral } from './compact-artifact-literal.mjs';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const hash = value => createHash('sha256').update(value).digest('hex');
const text = path => readFile(resolve(root, path), 'utf8');
export async function generateDeferredTiledProduction({ write = false } = {}) {
  const sourcePath = 'shader-language/src/deferred-lighting/tiled-family.ts';
  const { buildDeferredTiledPasses } = await loadPrivateBuildModule(sourcePath);
  const { DEFERRED_TILE_LAYOUT: layout } = await loadPrivateBuildModule('shader-language/src/deferred-lighting/tile-layout.ts');
  const { DEFERRED_LIGHTING_ABI_WGSL: abi } = await loadPrivateBuildModule('engine/src/shaders/generated/deferred-lighting-abi.generated.ts');
  const reference = await compileDeferredLightingArtifact();
  const constants = Object.entries({ TILE_SIZE: layout.tileSize, TILE_WORKGROUP_SIZE: layout.workgroupSize,
    TILE_CAPACITY: layout.capacity, TILE_HEADER_WORDS: layout.headerWords, TILE_STRIDE_WORDS: layout.strideWords })
    .map(([key, value]) => `const ${key}: u32 = ${value}u;`).join('\n');
  const modules = { abi, layout: constants + '\nstruct DeferredTileParameters { grid: vec4<u32>, viewport: vec4<f32>, }',
    scene: reference.passes['deferred-reference'].code.match(/struct FogUniforms\s*\{[^}]*\}/)[0] + '\n' + await text('shader-language/src/render-family/stdlib/simple-3d/scene-frame.wgsl'),
    cull: await text('shader-language/src/deferred-lighting/tile-cull.wgsl'),
    point: await text('shader-language/src/deferred-lighting/point-resolve.wgsl'),
    resolve: await text('shader-language/src/deferred-lighting/tile-resolve.wgsl') };
  const passes = buildDeferredTiledPasses(reference.passes['deferred-reference'], modules);
  const sourceHash = hash(await text(sourcePath));
  const moduleHash = hash(JSON.stringify({ sourceHash, modules, reference: reference.artifactHash }));
  const artifact = createPrecompiledShaderArtifactV2({ compilerVersion: 'shader-language-deferred-tiled-v1',
    source: { kind: 'module-family', path: sourcePath, sha256: sourceHash }, canonicalHash: moduleHash, typedModuleHash: moduleHash, passes });
  const directory = 'engine/src/shaders/generated/';
  const outputs = new Map(passes.map(pass => [`${directory}${pass.id}.generated.wgsl`, pass.code]));
  const data = structuredClone(artifact);
  for (const pass of Object.values(data.passes)) pass.code = `__SOURCE_${pass.id}__`;
  let literal = compactArtifactLiteral(data);
  const imports = passes.map((pass, i) => {
    literal = literal.replace(JSON.stringify(`__SOURCE_${pass.id}__`), `s${i}`);
    return `import s${i} from './${pass.id}.generated.wgsl';`;
  }).join('\n');
  outputs.set(`${directory}deferred-tiled-artifact.generated.ts`,
    '// Generated by shader-language/scripts/generate-deferred-tiled-production.mjs. Do not edit.\n'
    + "import type { PrecompiledShaderArtifactV2 } from '../../shader/PrecompiledShaderRuntime';\n"
    + imports + `\nexport const DEFERRED_TILED_SHADER_ARTIFACT = ${literal} as const satisfies PrecompiledShaderArtifactV2;\n`);
  outputs.set(`${directory}deferred-tile-layout.generated.ts`,
    '// Generated by shader-language/scripts/generate-deferred-tiled-production.mjs. Do not edit.\n'
    + `export const DEFERRED_TILE_LAYOUT = ${JSON.stringify(layout, null, 2)} as const;\n`);
  for (const [path, expected] of outputs) {
    if (write) await writeFile(resolve(root, path), expected);
    else if (await text(path).catch(() => null) !== expected) throw new Error(`Stale ${path}; run node shader-language/scripts/generate-deferred-tiled-production.mjs --write`);
  }
  return { id: 'deferred-tiled', artifactVersion: 2, outputCount: outputs.size, passCount: passes.length,
    artifactHash: artifact.artifactHash, wgslBytes: passes.reduce((n, p) => n + Buffer.byteLength(p.code), 0), artifact };
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { artifact, ...result } = await generateDeferredTiledProduction({ write: process.argv.includes('--write') });
  console.log(result);
}
