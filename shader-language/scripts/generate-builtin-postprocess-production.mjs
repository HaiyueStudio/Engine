import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compileBuiltinPostprocessFamilyV1 } from '../dist/index.js';

const directory = dirname(fileURLToPath(import.meta.url));
const root = resolve(directory, '../..');
const familyPath = resolve(root, 'shader-language/builtin-postprocess-family.json');
const outputDirectory = resolve(root, 'engine/src/shaders/generated');
const sourcePath = 'shader-language/builtin-postprocess-family.json';

export async function generateBuiltinPostprocessProduction({ write = false } = {}) {
  const source = await readFile(familyPath, 'utf8');
  const sourceHash = sha256(source);
  const compiled = compileBuiltinPostprocessFamilyV1(source, {
    sourcePath,
    sourceSha256: sourceHash,
    passGroup: 0,
  });
  const passFiles = Object.fromEntries(Object.keys(compiled.passes).map(pass => [
    pass,
    `postprocess-${pass}.generated.wgsl`,
  ]));
  const ambientOcclusionPasses = new Set(['ssao', 'sao', 'gtao', 'ao-denoise', 'ao-upscale']);
  const basePassFiles = Object.fromEntries(Object.entries(passFiles).filter(([pass]) => !ambientOcclusionPasses.has(pass)));
  const ambientOcclusionPassFiles = Object.fromEntries(Object.entries(passFiles).filter(([pass]) => ambientOcclusionPasses.has(pass)));
  const outputs = new Map([
    [resolve(outputDirectory, 'postprocess-fullscreen.generated.wgsl'), `${compiled.fullscreenVertexSource}\n`],
    ...Object.entries(passFiles).map(([pass, file]) => [
      resolve(outputDirectory, file),
      compiled.passes[pass].code,
    ]),
  ]);
  outputs.set(
    resolve(outputDirectory, 'postprocess-builtins-artifact.generated.ts'),
    renderManifest(sliceArtifact(compiled.artifact, Object.keys(basePassFiles)), basePassFiles, 'BUILTIN_POSTPROCESS_SHADER_ARTIFACT'),
  );
  outputs.set(
    resolve(outputDirectory, 'postprocess-ambient-occlusion-artifact.generated.ts'),
    renderManifest(
      sliceArtifact(compiled.artifact, Object.keys(ambientOcclusionPassFiles)),
      ambientOcclusionPassFiles,
      'AMBIENT_OCCLUSION_SHADER_ARTIFACT',
    ),
  );
  if (write) await mkdir(outputDirectory, { recursive: true });
  const stale = [];
  for (const [path, expected] of outputs) {
    if (write) {
      await writeFile(path, expected, 'utf8');
      continue;
    }
    let actual = null;
    try { actual = await readFile(path, 'utf8'); } catch { /* reported below */ }
    if (actual !== expected) stale.push(path);
  }
  if (stale.length > 0) {
    throw new Error(`Stale generated builtin postprocess artifacts:\n${stale.map(path => `- ${path}`).join('\n')}\nRun npm run shader-language:generate.`);
  }
  return Object.freeze({
    id: 'builtin-postprocess',
    artifactVersion: compiled.artifact.version,
    artifactHash: compiled.artifact.artifactHash,
    sourceHash,
    logicalGroups: Object.freeze([3]),
    physicalGroups: Object.freeze([0]),
    passCount: Object.keys(compiled.artifact.passes).length,
    outputCount: outputs.size,
  });
}

export function formatBuiltinPostprocessGenerationResult(result, write) {
  return `[shader-language:production:builtin-postprocess] ${write ? 'wrote' : 'verified'} ${result.outputCount} files, `
    + `passes=${result.passCount}, artifact=${result.artifactHash.slice(0, 12)}, family=${result.sourceHash.slice(0, 12)}, group=3->0.`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const write = process.argv.includes('--write');
  const result = await generateBuiltinPostprocessProduction({ write });
  console.log(formatBuiltinPostprocessGenerationResult(result, write));
}

function renderManifest(value, files, exportName) {
  const variables = Object.fromEntries(Object.keys(files).map(pass => [pass, sourceVariable(pass)]));
  const tokens = Object.fromEntries(Object.keys(files).map(pass => [pass, `__HAIYUE_SOURCE_${pass}__`]));
  const serializable = {
    ...value,
    passes: Object.fromEntries(Object.entries(value.passes).map(([pass, entry]) => [
      pass,
      { ...entry, code: tokens[pass] },
    ])),
  };
  let literal = JSON.stringify(serializable, null, 2);
  for (const pass of Object.keys(files)) {
    literal = literal.replace(JSON.stringify(tokens[pass]), variables[pass]);
  }
  const imports = Object.entries(files)
    .map(([pass, file]) => `import ${variables[pass]} from './${file}';`)
    .join('\n');
  return `// Generated by shader-language/scripts/generate-builtin-postprocess-production.mjs. Do not edit.\n`
    + `import type { PrecompiledShaderArtifactV2 } from '../../shader/PrecompiledShaderRuntime';\n`
    + `${imports}\n\n`
    + `export const ${exportName} = ${literal} as const satisfies PrecompiledShaderArtifactV2;\n`;
}

function sliceArtifact(artifact, passIds) {
  return {
    ...artifact,
    passes: Object.fromEntries(passIds.map(pass => [pass, artifact.passes[pass]])),
  };
}

function sourceVariable(pass) {
  return `${pass.replace(/-([a-z])/g, (_match, letter) => letter.toUpperCase())}Wgsl`;
}

function sha256(value) {
  return createHash('sha256').update(value).digest('hex');
}
