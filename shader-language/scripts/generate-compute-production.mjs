import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compileProductionComputeFamilyV1 } from '../dist/index.js';

const directory = dirname(fileURLToPath(import.meta.url));
const root = resolve(directory, '../..');
const sourcePath = 'shader-language/builtin-compute-family.json';
const outputDirectory = resolve(root, 'engine/src/shaders/generated');

export async function generateComputeProduction({ write = false } = {}) {
  const source = await readFile(resolve(root, sourcePath), 'utf8');
  const compiled = compileProductionComputeFamilyV1(source, { sourcePath, sourceSha256: sha256(source) });
  const passFiles = Object.fromEntries(Object.keys(compiled.passes).map(pass => [pass, `compute-${pass}.generated.wgsl`]));
  const outputs = new Map(Object.entries(passFiles).map(([pass, file]) => [resolve(outputDirectory, file), compiled.passes[pass].code]));
  outputs.set(resolve(outputDirectory, 'compute-artifact.generated.ts'), renderArtifact(compiled.artifact, passFiles));
  if (write) await mkdir(outputDirectory, { recursive: true });
  const stale = [];
  for (const [path, expected] of outputs) {
    if (write) { await writeFile(path, expected, 'utf8'); continue; }
    let actual = null;
    try { actual = await readFile(path, 'utf8'); } catch { /* reported below */ }
    if (actual !== expected) stale.push(path);
  }
  if (stale.length > 0) throw new Error(`Stale generated compute artifacts:\n${stale.map(path => `- ${path}`).join('\n')}\nRun npm run shader-language:generate.`);
  return Object.freeze({ id: 'compute', artifactVersion: 2, passCount: Object.keys(compiled.passes).length, outputCount: outputs.size, artifactHash: compiled.artifact.artifactHash, computeModuleHash: compiled.computeModuleHash });
}

export function formatComputeGenerationResult(result, write) {
  return `[shader-language:production:compute] ${write ? 'wrote' : 'verified'} ${result.outputCount} files, passes=${result.passCount}, ABI=1, module=${result.computeModuleHash.slice(0, 12)}.`;
}

function renderArtifact(value, files) {
  const variables = Object.fromEntries(Object.keys(files).map(pass => [pass, sourceVariable(pass)]));
  const tokens = Object.fromEntries(Object.keys(files).map(pass => [pass, `__HAIYUE_SOURCE_${pass}__`]));
  const serializable = { ...value, passes: Object.fromEntries(Object.entries(value.passes).map(([pass, entry]) => [pass, { ...entry, code: tokens[pass] }])) };
  let literal = JSON.stringify(serializable, null, 2);
  for (const pass of Object.keys(files)) literal = literal.replace(JSON.stringify(tokens[pass]), variables[pass]);
  const imports = Object.entries(files).map(([pass, file]) => `import ${variables[pass]} from './${file}';`).join('\n');
  return '// Generated by shader-language/scripts/generate-compute-production.mjs. Do not edit.\n'
    + "import type { PrecompiledShaderArtifactV2 } from '../../shader/PrecompiledShaderRuntime';\n"
    + `${imports}\n\n`
    + `export const COMPUTE_SHADER_ARTIFACT = ${literal} as const satisfies PrecompiledShaderArtifactV2;\n`;
}

function sourceVariable(pass) {
  return `${pass.replace(/-([a-z0-9])/g, (_match, value) => value.toUpperCase()).replace(/^[a-z]/, value => value.toUpperCase())}Wgsl`;
}
function sha256(value) { return createHash('sha256').update(value).digest('hex'); }

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const write = process.argv.includes('--write');
  console.log(formatComputeGenerationResult(await generateComputeProduction({ write }), write));
}
