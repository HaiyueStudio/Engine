import { readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import ts from 'typescript';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const sourcePath = 'shader-language/src/deferred-lighting/abi.ts';

export async function generateDeferredLightingAbi({ write = false } = {}) {
  const source = await readFile(resolve(root, sourcePath), 'utf8');
  const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext } }).outputText;
  const { DEFERRED_LIGHTING_ABI: abi } = await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);
  const hash = createHash('sha256').update(source).digest('hex');
  const declarations = [];
  const writers = [];
  for (const block of Object.values(abi.blocks)) {
    let offset = 0;
    for (const field of block.fields) {
      const vector = field.type.startsWith('vec4');
      const alignment = vector ? 16 : 4;
      offset = Math.ceil(offset / alignment) * alignment;
      if (field.offset !== offset) throw new Error(`${block.name}.${field.name}: invalid offset ${field.offset}, expected ${offset}`);
      offset += vector ? 16 : 4;
    }
    if (Math.ceil(offset / block.alignment) * block.alignment !== block.byteSize) throw new Error(`${block.name}: invalid size`);
    declarations.push(`struct ${block.name} {\n${block.fields.map(f => `  ${f.name}: ${f.type},`).join('\n')}\n}`);
    writers.push(`export interface ${block.name}Input {\n${block.fields.map(f => `  readonly ${f.name}: ${f.type.startsWith('vec4') ? 'readonly [number, number, number, number]' : 'number'};`).join('\n')}\n}\n`
      + `export function write${block.name}(out: DataView, offset: number, value: ${block.name}Input): void {\n`
      + `  if (!Number.isInteger(offset) || offset < 0 || offset % ${block.alignment} !== 0 || offset + ${block.byteSize} > out.byteLength) throw new RangeError('${block.name}: invalid destination');\n`
      + block.fields.flatMap(f => Array.from({ length: f.type.startsWith('vec4') ? 4 : 1 }, (_, i) => {
        const expression = `value.${f.name}${f.type.startsWith('vec4') ? `[${i}]` : ''}`;
        const uint = f.type.includes('u32');
        return `  out.${uint ? 'setUint32' : 'setFloat32'}(offset + ${f.offset + 4 * i}, ${uint ? 'uint32' : 'float32'}(${expression}), true);`;
      })).join('\n') + '\n}\n');
  }
  const output = '// Generated by shader-language/scripts/generate-deferred-lighting-abi.mjs. Do not edit.\n'
    + `// source: ${sourcePath}; sha256: ${hash}\n`
    + `export const DEFERRED_LIGHTING_ABI = ${JSON.stringify(abi, null, 2)} as const;\n`
    + `export const DEFERRED_LIGHTING_ABI_WGSL = ${JSON.stringify(declarations.join('\n\n') + '\n')} ;\n`
    + writers.join('\n')
    + `\nfunction uint32(value: number): number {\n  if (!Number.isInteger(value) || value < 0 || value > 0xffffffff) throw new RangeError('Deferred ABI: invalid u32');\n  return value;\n}\n`
    + `\nfunction float32(value: number): number {\n  if (!Number.isFinite(Math.fround(value))) throw new RangeError('Deferred ABI: invalid f32');\n  return value;\n}\n`;
  const path = resolve(root, 'engine/src/shaders/generated/deferred-lighting-abi.generated.ts');
  if (write) await writeFile(path, output);
  else if (await readFile(path, 'utf8').catch(() => null) !== output) throw new Error('Stale Deferred light ABI; run node shader-language/scripts/generate-deferred-lighting-abi.mjs --write');
  return { id: 'deferred-lighting-abi', outputCount: 1, sourceSha256: hash };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(await generateDeferredLightingAbi({ write: process.argv.includes('--write') }));
}
