import {readFile,writeFile} from 'node:fs/promises';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {compileProductionMaterialLightingFamilyV1,createPrecompiledShaderArtifactV2} from '../dist/index.js';
import {loadPrivateBuildModule} from './generate-deferred-lighting-production.mjs';
import {emitLineVariantExpression} from './shader-source-variant.mjs';
import {compactArtifactLiteral} from './compact-artifact-literal.mjs';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'../..');
const text=path=>readFile(resolve(root,path),'utf8'),hash=value=>createHash('sha256').update(value).digest('hex');
export async function compileDeferredFullForwardArtifact(){
  const sourcePath='shader-language/src/deferred-lighting/full-forward-family.ts';
  const {buildFullForwardPass}=await loadPrivateBuildModule(sourcePath);
  const {DEFERRED_LIGHTING_ABI_WGSL:abi,DEFERRED_LIGHTING_ABI:layout}=await loadPrivateBuildModule('engine/src/shaders/generated/deferred-lighting-abi.generated.ts');
  const basePath='shader-language/builtin-material-lighting-family.json',source=await text(basePath);
  const base=compileProductionMaterialLightingFamilyV1(source,{sourcePath:basePath,sourceSha256:hash(source)}).artifact;
  const modules={abi,lightingAo:await text('shader-language/src/deferred-lighting/lighting-ao.wgslinc'),lights:await text('shader-language/src/deferred-lighting/full-forward.wgsl'),viewHeader:{id:'pass.fullView',alignment:16,byteSize:32,
    fields:layout.blocks.viewHeader.fields.map(field=>({...field,size:field.type.startsWith('vec4')?16:4}))}};
  const sourceHash=hash(await text(sourcePath)),moduleHash=hash(JSON.stringify({modules,sourceHash,base:base.artifactHash}));
  const passes=['pbr','pbr-clearcoat','pbr-transmission','pbr-transmission-clearcoat'].map(id=>buildFullForwardPass(base.passes[id],modules));
  return createPrecompiledShaderArtifactV2({compilerVersion:'shader-language-deferred-full-forward-v1',source:{kind:'module-family',path:sourcePath,sha256:sourceHash},canonicalHash:moduleHash,typedModuleHash:moduleHash,passes});
}
export async function generateDeferredFullForwardProduction({write=false}={}){
  const artifact=await compileDeferredFullForwardArtifact(),passes=Object.values(artifact.passes),directory='engine/src/shaders/generated/';
  const outputs=new Map(passes.map(pass=>[`${directory}${pass.id}.generated.wgsl`,pass.code]));
  const data=structuredClone(artifact);for(const pass of Object.values(data.passes))pass.code=`__SOURCE_${pass.id}__`;
  const fields=['bindGroups','uniformBlocks','vertexBuffers','varyings','renderTargets'];
  for(const field of fields)for(const pass of passes){
    if(JSON.stringify(pass[field])!==JSON.stringify(passes[0][field]))throw Error(`Full Forward shared reflection drift: ${pass.id}.${field}`);
    data.passes[pass.id][field]=`__SHARED_${field}__`;
  }
  let literal=compactArtifactLiteral(data);
  for(const [i,pass] of passes.entries())literal=literal.replace(JSON.stringify(`__SOURCE_${pass.id}__`),`s${i}`);
  const declarations=fields.map((field,i)=>{
    literal=literal.replaceAll(JSON.stringify(`__SHARED_${field}__`),`r${i}`);
    return `const r${i} = ${compactArtifactLiteral(passes[0][field])} as const;`;
  }).join('\n');
  const imports=`import s0 from './${passes[0].id}.generated.wgsl';\n`
    +passes.slice(1).map((pass,i)=>`const s${i+1} = ${emitLineVariantExpression('s0',passes[0].code,pass.code)};`).join('\n')+'\n'+declarations;
  outputs.set(`${directory}deferred-full-forward-artifact.generated.ts`,
    '// Generated by shader-language/scripts/generate-deferred-full-forward-production.mjs. Do not edit.\n'
    +"import type { PrecompiledShaderArtifactV2 } from '../../shader/PrecompiledShaderRuntime';\n"
    +imports+`\nexport const DEFERRED_FULL_FORWARD_SHADER_ARTIFACT = ${literal} as const satisfies PrecompiledShaderArtifactV2;\n`);
  for(const [path,expected] of outputs){if(write)await writeFile(resolve(root,path),expected);else if(await text(path).catch(()=>null)!==expected)throw Error(`Stale ${path}; run node shader-language/scripts/generate-deferred-full-forward-production.mjs --write`);}
  return {id:'deferred-full-forward',artifactVersion:2,outputCount:outputs.size,passCount:passes.length,artifactHash:artifact.artifactHash,wgslBytes:passes.reduce((n,p)=>n+Buffer.byteLength(p.code),0),artifact};
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){const {artifact,...result}=await generateDeferredFullForwardProduction({write:process.argv.includes('--write')});console.log(result);}
