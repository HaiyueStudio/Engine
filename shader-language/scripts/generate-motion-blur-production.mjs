import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  compileMotionBlurGraphV1,
  createMotionBlurPrecompiledArtifactV2,
} from '../dist/index.js';

const directory = dirname(fileURLToPath(import.meta.url));
const root = resolve(directory, '../..');
const graphPath = resolve(root, 'shader-language/pilot-motion-blur-postprocess.graph.json');
const stage5ContractPath = resolve(root, 'shader-language/stage5-contract.json');
const outputDirectory = resolve(root, 'engine/src/shaders/generated');

export async function generateMotionBlurProduction({ write = false } = {}) {
  const graphSource = await readFile(graphPath, 'utf8');
  const stage5Contract = JSON.parse(await readFile(stage5ContractPath, 'utf8'));
  const graphSha256 = sha256(graphSource);
  if (stage5Contract.graph?.sha256 !== graphSha256) {
    throw new Error('Stage 5 graph provenance is stale; update its reviewed contract before production generation.');
  }
  const compiled = compileMotionBlurGraphV1(graphSource, {
    id: stage5Contract.graph.programId,
    sourceName: 'pilot-motion-blur-postprocess.graph.json',
    passGroup: 0,
  });
  const artifact = createMotionBlurPrecompiledArtifactV2(compiled, {
    sourceGraphPath: 'shader-language/pilot-motion-blur-postprocess.graph.json',
    sourceGraphSha256: graphSha256,
  });
  const passFiles = Object.freeze({
    'motion-tile-max': 'motion-tile-max.generated.wgsl',
    'motion-neighbor-max': 'motion-neighbor-max.generated.wgsl',
    'motion-blur-resolve': 'motion-blur-resolve.generated.wgsl',
  });
  const outputs = new Map(Object.entries(passFiles).map(([pass, file]) => [
    resolve(outputDirectory, file),
    artifact.passes[pass].code,
  ]));
  outputs.set(resolve(outputDirectory, 'motion-blur-artifact.generated.ts'), renderManifest(artifact, passFiles));
  if (write) await mkdir(outputDirectory, { recursive: true });
  const stale = [];
  for (const [path, expected] of outputs) {
    if (write) {
      await writeFile(path, expected, 'utf8');
      continue;
    }
    let actual = null;
    try { actual = await readFile(path, 'utf8'); } catch { /* reported as stale */ }
    if (actual !== expected) stale.push(path);
  }
  if (stale.length > 0) {
    throw new Error(`Stale generated Motion Blur artifacts:\n${stale.map(path => `- ${path}`).join('\n')}\nRun npm run shader-language:generate.`);
  }
  return Object.freeze({
    id: 'motion-blur', artifactVersion: artifact.version, artifactHash: artifact.artifactHash,
    sourceHash: graphSha256, logicalGroups: Object.freeze([3]), physicalGroups: Object.freeze([0]),
    outputCount: outputs.size,
  });
}

export function formatMotionBlurGenerationResult(result, write) {
  return `[shader-language:production:motion-blur] ${write ? 'wrote' : 'verified'} ${result.outputCount} files, `
    + `artifact=${result.artifactHash.slice(0, 12)}, graph=${result.sourceHash.slice(0, 12)}, group=3->0.`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const write = process.argv.includes('--write');
  const result = await generateMotionBlurProduction({ write });
  console.log(formatMotionBlurGenerationResult(result, write));
}

function renderManifest(value, files) {
  const variables = Object.fromEntries(Object.keys(files).map(pass => [pass, sourceVariable(pass)]));
  const tokens = Object.fromEntries(Object.keys(files).map(pass => [pass, `__HAIYUE_SOURCE_${pass}__`]));
  const serializable = {
    ...value,
    passes: Object.fromEntries(Object.entries(value.passes).map(([pass, entry]) => [
      pass,
      { ...entry, code: tokens[pass] },
    ])),
  };
  let literal = JSON.stringify(serializable, null, 2);
  for (const pass of Object.keys(files)) {
    literal = literal.replace(JSON.stringify(tokens[pass]), variables[pass]);
  }
  const imports = Object.entries(files)
    .map(([pass, file]) => `import ${variables[pass]} from './${file}';`)
    .join('\n');
  return `// Generated by shader-language/scripts/generate-motion-blur-production.mjs. Do not edit.\n`
    + `import type { PrecompiledShaderArtifactV2 } from '../../shader/PrecompiledShaderRuntime';\n`
    + `${imports}\n\n`
    + `export const MOTION_BLUR_SHADER_ARTIFACT = ${literal} as const satisfies PrecompiledShaderArtifactV2;\n`;
}

function sourceVariable(pass) {
  return `${pass.replace(/-([a-z])/g, (_match, letter) => letter.toUpperCase())}Wgsl`;
}

function sha256(value) {
  return createHash('sha256').update(value).digest('hex');
}
