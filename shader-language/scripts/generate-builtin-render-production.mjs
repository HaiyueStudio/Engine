import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compileBuiltinRenderFamilyV1 } from '../dist/index.js';

const directory = dirname(fileURLToPath(import.meta.url));
const root = resolve(directory, '../..');
const families = Object.freeze([
  Object.freeze({
    id: 'engine-2d-ui',
    source: 'shader-language/builtin-engine-2d-ui-family.json',
    output: 'engine/src/shaders/generated',
    prefix: '2d-ui',
    typed: true,
  }),
  Object.freeze({
    id: 'components-2d-ui',
    source: 'shader-language/builtin-components-2d-ui-family.json',
    output: 'extensions/src/shaders/generated',
    prefix: '2d-ui',
    typed: false,
  }),
  Object.freeze({
    id: 'simple-3d',
    source: 'shader-language/builtin-simple-3d-runtime-family.json',
    output: 'engine/src/shaders/generated',
    prefix: 'simple3d',
    typed: true,
  }),
]);

export async function generateBuiltinRenderProduction({ write = false } = {}) {
  const summaries = [];
  for (const family of families) summaries.push(await generateFamily(family, write));
  return Object.freeze({
    id: 'builtin-render',
    artifactVersion: 2,
    familyCount: summaries.length,
    passCount: summaries.reduce((sum, value) => sum + value.passCount, 0),
    outputCount: summaries.reduce((sum, value) => sum + value.outputCount, 0),
    families: Object.freeze(summaries),
  });
}

export function formatBuiltinRenderGenerationResult(result, write) {
  const hashes = result.families.map(family => `${family.id}:${family.artifactHash.slice(0, 10)}`).join(',');
  return `[shader-language:production:builtin-render] ${write ? 'wrote' : 'verified'} `
    + `${result.outputCount} files, families=${result.familyCount}, passes=${result.passCount}, artifacts=${hashes}.`;
}

async function generateFamily(config, write) {
  const absoluteSource = resolve(root, config.source);
  const outputDirectory = resolve(root, config.output);
  const source = await readFile(absoluteSource, 'utf8');
  const sourceHash = sha256(source);
  const compiled = compileBuiltinRenderFamilyV1(source, {
    sourcePath: config.source,
    sourceSha256: sourceHash,
  });
  const passFiles = Object.fromEntries(Object.keys(compiled.passes).map(pass => [
    pass,
    `${config.prefix}-${pass}.generated.wgsl`,
  ]));
  const outputs = new Map(Object.entries(passFiles).map(([pass, file]) => [
    resolve(outputDirectory, file),
    compiled.passes[pass].code,
  ]));
  outputs.set(
    resolve(outputDirectory, `${config.prefix}-artifact.generated.ts`),
    renderArtifact(compiled.artifact, passFiles, config.typed),
  );
  if (write) await mkdir(outputDirectory, { recursive: true });
  const stale = [];
  for (const [path, expected] of outputs) {
    if (write) {
      await writeFile(path, expected, 'utf8');
      continue;
    }
    let actual = null;
    try { actual = await readFile(path, 'utf8'); } catch { /* reported below */ }
    if (actual !== expected) stale.push(path);
  }
  if (stale.length > 0) {
    throw new Error(`Stale generated ${config.id} artifacts:\n${stale.map(path => `- ${path}`).join('\n')}\nRun npm run shader-language:generate.`);
  }
  return Object.freeze({
    id: config.id,
    artifactHash: compiled.artifact.artifactHash,
    sourceHash,
    passCount: Object.keys(compiled.passes).length,
    outputCount: outputs.size,
  });
}

function renderArtifact(value, files, typed) {
  const variables = Object.fromEntries(Object.keys(files).map(pass => [pass, sourceVariable(pass)]));
  const tokens = Object.fromEntries(Object.keys(files).map(pass => [pass, `__HAIYUE_SOURCE_${pass}__`]));
  const serializable = {
    ...value,
    passes: Object.fromEntries(Object.entries(value.passes).map(([pass, entry]) => [
      pass,
      { ...entry, code: tokens[pass] },
    ])),
  };
  let literal = JSON.stringify(serializable, null, 2);
  for (const pass of Object.keys(files)) {
    literal = literal.replace(JSON.stringify(tokens[pass]), variables[pass]);
  }
  const imports = Object.entries(files)
    .map(([pass, file]) => `import ${variables[pass]} from './${file}';`)
    .join('\n');
  const typeImport = typed
    ? `import type { PrecompiledShaderArtifactV2 } from '../../shader/PrecompiledShaderRuntime';\n`
    : '';
  const assertion = typed ? ' as const satisfies PrecompiledShaderArtifactV2' : ' as const';
  return `// Generated by shader-language/scripts/generate-builtin-render-production.mjs. Do not edit.\n`
    + typeImport
    + `${imports}\n\n`
    + `export const BUILTIN_RENDER_SHADER_ARTIFACT = ${literal}${assertion};\n`;
}

function sourceVariable(pass) {
  return `${pass.replace(/-([a-z0-9])/g, (_match, value) => value.toUpperCase()).replace(/^[a-z]/, value => value.toUpperCase())}Wgsl`;
}

function sha256(value) {
  return createHash('sha256').update(value).digest('hex');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const write = process.argv.includes('--write');
  const result = await generateBuiltinRenderProduction({ write });
  console.log(formatBuiltinRenderGenerationResult(result, write));
}
