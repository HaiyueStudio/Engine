import { readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import ts from 'typescript';
import { compileProductionMaterialLightingFamilyV1, createPrecompiledShaderArtifactV2 } from '../dist/index.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const hash = value => createHash('sha256').update(value).digest('hex');
async function text(path) { return readFile(resolve(root, path), 'utf8'); }
export async function loadPrivateBuildModule(path) {
  const source = await text(path);
  const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext } }).outputText;
  return import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);
}

export async function compileDeferredLightingArtifact() {
  const sourcePath = 'shader-language/src/deferred-lighting/family.ts';
  const { buildDeferredLightingPasses } = await loadPrivateBuildModule(sourcePath);
  const { DEFERRED_LIGHTING_ABI_WGSL, DEFERRED_LIGHTING_ABI } = await loadPrivateBuildModule('engine/src/shaders/generated/deferred-lighting-abi.generated.ts');
  const baseSourcePath = 'shader-language/builtin-material-lighting-family.json';
  const source = await text(baseSourcePath);
  const base = compileProductionMaterialLightingFamilyV1(source, { sourcePath: baseSourcePath, sourceSha256: hash(source) });
  const modules = {
    lightingAo: await text('shader-language/src/deferred-lighting/lighting-ao.wgslinc'),
    geometry: await text('shader-language/src/deferred-lighting/gbuffer.wgsl'),
    resolve: await text('shader-language/src/deferred-lighting/resolve.wgsl'),
    abi: DEFERRED_LIGHTING_ABI_WGSL,
    scene: await text('shader-language/src/render-family/stdlib/simple-3d/scene-frame.wgsl'),
    fog: base.featureModules.fog,
    brdf: base.featureModules.pbrBrdf,
    shadow: await text('shader-language/src/material-lighting/stdlib/pbr-shadow.wgsl'),
    viewHeader: { id: 'pass.view', alignment: DEFERRED_LIGHTING_ABI.blocks.viewHeader.alignment,
      byteSize: DEFERRED_LIGHTING_ABI.blocks.viewHeader.byteSize,
      fields: DEFERRED_LIGHTING_ABI.blocks.viewHeader.fields.map(field => ({ ...field, size: field.type.startsWith('vec4') ? 16 : 4 })) },
  };
  const passes = buildDeferredLightingPasses(base.artifact.passes.pbr, modules);
  const sourceHash = hash(await text(sourcePath));
  const moduleHash = hash(JSON.stringify({ sourceHash, modules, base: base.artifact.artifactHash }));
  const artifact = createPrecompiledShaderArtifactV2({
    compilerVersion: 'shader-language-deferred-abi-v1', source: { kind: 'module-family', path: sourcePath, sha256: sourceHash },
    canonicalHash: moduleHash, typedModuleHash: moduleHash, passes,
  });
  return artifact;
}

export async function generateDeferredLightingProduction({ write = false } = {}) {
  const artifact = await compileDeferredLightingArtifact();
  const passes = Object.values(artifact.passes);
  const directory = 'engine/src/shaders/generated/';
  const outputs = new Map(passes.map(pass => [`${directory}${pass.id}.generated.wgsl`, pass.code]));
  const serializable = structuredClone(artifact);
  for (const pass of Object.values(serializable.passes)) pass.code = `__SOURCE_${pass.id}__`;
  let literal = JSON.stringify(serializable, null, 2);
  const imports = passes.map((pass, i) => {
    literal = literal.replace(JSON.stringify(`__SOURCE_${pass.id}__`), `source${i}`);
    return `import source${i} from './${pass.id}.generated.wgsl';`;
  }).join('\n');
  outputs.set(`${directory}deferred-lighting-artifact.generated.ts`,
    '// Generated by shader-language/scripts/generate-deferred-lighting-production.mjs. Do not edit.\n'
    + "import type { PrecompiledShaderArtifactV2 } from '../../shader/PrecompiledShaderRuntime';\n"
    + imports + `\nexport const DEFERRED_LIGHTING_SHADER_ARTIFACT = ${literal} as const satisfies PrecompiledShaderArtifactV2;\n`);
  for (const [path, expected] of outputs) {
    if (write) await writeFile(resolve(root, path), expected);
    else if (await text(path).catch(() => null) !== expected) throw new Error(`Stale ${path}; run node shader-language/scripts/generate-deferred-lighting-production.mjs --write`);
  }
  return { id: 'deferred-lighting', artifactVersion: 2, outputCount: outputs.size, passCount: passes.length,
    artifactHash: artifact.artifactHash, wgslBytes: passes.reduce((n, p) => n + Buffer.byteLength(p.code), 0),
    passes: passes.map(p => ({ id: p.id, wgslBytes: Buffer.byteLength(p.code) })) };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(await generateDeferredLightingProduction({ write: process.argv.includes('--write') }));
}
