import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compileProductionMaterialLightingFamilyV1 } from '../dist/index.js';

const directory = dirname(fileURLToPath(import.meta.url));
const root = resolve(directory, '../..');
const sourcePath = 'shader-language/builtin-material-lighting-family.json';
const outputDirectory = resolve(root, 'engine/src/shaders/generated');

export async function generateMaterialLightingProduction({ write = false } = {}) {
  const source = await readFile(resolve(root, sourcePath), 'utf8');
  const compiled = compileProductionMaterialLightingFamilyV1(source, {
    sourcePath,
    sourceSha256: sha256(source),
  });
  const passFiles = Object.fromEntries(Object.keys(compiled.passes).map(pass => [
    pass,
    `material-lighting-${pass}.generated.wgsl`,
  ]));
  const outputs = new Map(Object.entries(passFiles).map(([pass, file]) => [
    resolve(outputDirectory, file),
    compiled.passes[pass].code,
  ]));
  outputs.set(resolve(outputDirectory, 'material-lighting-fog.generated.wgsl'), generatedFeature(
    'fog',
    compiled.lightingModuleHash,
    compiled.featureModules.fog,
  ));
  outputs.set(resolve(outputDirectory, 'material-lighting-pbr-brdf.generated.wgsl'), generatedFeature(
    'pbr-brdf',
    compiled.lightingModuleHash,
    compiled.featureModules.pbrBrdf,
  ));
  outputs.set(
    resolve(outputDirectory, 'material-lighting-artifact.generated.ts'),
    renderArtifact(compiled.artifact, passFiles),
  );
  if (write) await mkdir(outputDirectory, { recursive: true });
  const stale = [];
  for (const [path, expected] of outputs) {
    if (write) {
      await writeFile(path, expected, 'utf8');
      continue;
    }
    let actual = null;
    try { actual = await readFile(path, 'utf8'); } catch { /* reported below */ }
    if (actual !== expected) stale.push(path);
  }
  if (stale.length > 0) {
    throw new Error(`Stale generated material-lighting artifacts:\n${stale.map(path => `- ${path}`).join('\n')}\nRun npm run shader-language:generate.`);
  }
  return Object.freeze({
    id: 'material-lighting',
    artifactVersion: 2,
    passCount: Object.keys(compiled.passes).length,
    outputCount: outputs.size,
    artifactHash: compiled.artifact.artifactHash,
    lightingModuleHash: compiled.lightingModuleHash,
    deformationModuleHash: compiled.deformationModuleHash,
  });
}

export function formatMaterialLightingGenerationResult(result, write) {
  return `[shader-language:production:material-lighting] ${write ? 'wrote' : 'verified'} `
    + `${result.outputCount} files, passes=${result.passCount}, ABI=1, lighting=${result.lightingModuleHash.slice(0, 12)}.`;
}

function generatedFeature(id, hash, source) {
  return '// Generated by shader-language/scripts/generate-material-lighting-production.mjs. Do not edit.\n'
    + `// haiyue:material-lighting-feature ${id}\n`
    + '// haiyue:material-lighting-abi 1\n'
    + `// haiyue:material-lighting-module ${hash}\n\n${source}`;
}

function renderArtifact(value, files) {
  const variables = Object.fromEntries(Object.keys(files).map(pass => [pass, sourceVariable(pass)]));
  const tokens = Object.fromEntries(Object.keys(files).map(pass => [pass, `__HAIYUE_SOURCE_${pass}__`]));
  const pbrPasses = ['pbr', 'pbr-clearcoat', 'pbr-transmission', 'pbr-transmission-clearcoat'];
  const sharedPbrProperties = [
    ['PBR_BIND_GROUPS', 'bindGroups'],
    ['PBR_UNIFORM_BLOCKS', 'uniformBlocks'],
    ['PBR_VERTEX_BUFFERS', 'vertexBuffers'],
    ['PBR_VARYINGS', 'varyings'],
    ['PBR_RENDER_TARGETS', 'renderTargets'],
  ];
  const serializablePasses = Object.fromEntries(Object.entries(value.passes).map(([pass, entry]) => [
    pass,
    { ...entry, code: tokens[pass] },
  ]));
  for (const pass of pbrPasses) {
    for (const [name, property] of sharedPbrProperties) {
      serializablePasses[pass][property] = `__HAIYUE_SHARED_${name}__`;
    }
  }
  const serializable = {
    ...value,
    passes: serializablePasses,
  };
  let literal = JSON.stringify(serializable, null, 2);
  for (const pass of Object.keys(files)) literal = literal.replace(JSON.stringify(tokens[pass]), variables[pass]);
  for (const [name] of sharedPbrProperties) {
    literal = literal.replaceAll(JSON.stringify(`__HAIYUE_SHARED_${name}__`), name);
  }
  const imports = Object.entries(files)
    .map(([pass, file]) => `import ${variables[pass]} from './${file}';`)
    .join('\n');
  const sharedDeclarations = sharedPbrProperties
    .map(([name, property]) => `const ${name} = ${JSON.stringify(value.passes.pbr[property], null, 2)} as const;`)
    .join('\n\n');
  return '// Generated by shader-language/scripts/generate-material-lighting-production.mjs. Do not edit.\n'
    + "import type { PrecompiledShaderArtifactV2 } from '../../shader/PrecompiledShaderRuntime';\n"
    + `${imports}\n\n${sharedDeclarations}\n\n`
    + `export const MATERIAL_LIGHTING_SHADER_ARTIFACT = ${literal} as const satisfies PrecompiledShaderArtifactV2;\n`;
}

function sourceVariable(pass) {
  return `${pass.replace(/-([a-z0-9])/g, (_match, value) => value.toUpperCase()).replace(/^[a-z]/, value => value.toUpperCase())}Wgsl`;
}

function sha256(value) {
  return createHash('sha256').update(value).digest('hex');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const write = process.argv.includes('--write');
  const result = await generateMaterialLightingProduction({ write });
  console.log(formatMaterialLightingGenerationResult(result, write));
}
