import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const shaderLanguageEntry = resolve(root, 'shader-language/dist/index.js');
if (!existsSync(shaderLanguageEntry)) {
  execFileSync(process.platform === 'win32' ? 'npm.cmd' : 'npm', ['run', 'build', '-w', './shader-language'], { cwd: root, stdio: 'inherit' });
}
const { createPrecompiledShaderArtifactV2 } = await import(new URL('../shader-language/dist/index.js', import.meta.url));
const familyPath = 'extensions/src/ray-tracing/shaders/ray-traversal-family.json';
const wgslPath = 'extensions/src/ray-tracing/shaders/ray-traversal.wgsl';
const tsOutput = 'extensions/src/ray-tracing/shaders/ray-traversal-artifact.generated.ts';
const browserOutput = 'scripts/webgpu-gate/ray-traversal-artifact.generated.mjs';

const familySource = await readFile(resolve(root, familyPath), 'utf8');
const wgsl = await readFile(resolve(root, wgslPath), 'utf8');
const family = JSON.parse(familySource);
validateFamily(family);

const canonicalHash = sha256(JSON.stringify(family));
const lineCount = wgsl.split(/\r?\n/u).length;
const artifact = createPrecompiledShaderArtifactV2({
  compilerVersion: 'shader-language-ray-traversal-v1',
  source: { kind: 'module-family', path: familyPath, sha256: sha256(familySource) },
  canonicalHash,
  typedModuleHash: sha256(`${canonicalHash}\n${sha256(wgsl)}`),
  passes: [{
    id: family.id,
    code: wgsl,
    entryPoints: { compute: family.entryPoint },
    bindGroups: [{
      logicalSpace: 'pass', logicalGroup: 3, physicalGroup: 0, owner: 'artifact',
      bindings: family.bindings.map(binding => ({
        id: binding.id,
        binding: binding.binding,
        visibility: ['compute'],
        layout: { kind: 'buffer', bufferType: binding.bufferType, hasDynamicOffset: false, minBindingSize: binding.minBindingSize },
      })),
    }],
    uniformBlocks: [{
      id: 'pass.params', alignment: 16, byteSize: 32,
      fields: [
        'rayCount', 'rayOffset', 'outputOffset', 'mode', 'tlasRoot', 'stackLimit', 'instanceCount', 'reserved',
      ].map((name, index) => ({ name, type: 'u32', offset: index * 4, size: 4 })),
    }],
    vertexBuffers: [], varyings: [], renderTargets: [], capabilities: ['compute', 'storage-buffer'],
    passRequirements: ['webgpu', 'maxStorageBuffersPerShaderStage>=8', 'maxBindingsPerBindGroup>=9'],
    sourceMap: [{ sourceId: family.id, sourceName: wgslPath, generatedStartLine: 1, generatedEndLine: lineCount, sourceStartLine: 1, sourceStartColumn: 1 }],
  }],
});

const banner = '// Generated by scripts/verify-ray-traversal-shader.mjs. Do not edit.\n';
const literal = JSON.stringify(artifact, null, 2);
const expectedTs = `${banner}export const RAY_TRAVERSAL_SHADER_ARTIFACT = ${literal} as const;\n`;
const expectedBrowser = `${banner}export const RAY_TRAVERSAL_SHADER_ARTIFACT = ${literal};\n`;
const write = process.argv.includes('--write');
if (write) {
  await writeFile(resolve(root, tsOutput), expectedTs, 'utf8');
  await writeFile(resolve(root, browserOutput), expectedBrowser, 'utf8');
} else {
  await verify(tsOutput, expectedTs);
  await verify(browserOutput, expectedBrowser);
}
console.log(`[ray-traversal:shader] ${write ? 'wrote' : 'verified'} Artifact V2 ${artifact.artifactHash.slice(0, 16)}, bindings=${family.bindings.length}, WGSL=${wgsl.length} bytes.`);

async function verify(path, expected) {
  let actual = null;
  try { actual = await readFile(resolve(root, path), 'utf8'); } catch { /* classified below */ }
  if (actual !== expected) throw new Error(`Stale ray traversal shader artifact: ${path}. Run node scripts/verify-ray-traversal-shader.mjs --write.`);
}
function sha256(value) { return createHash('sha256').update(value).digest('hex'); }
function validateFamily(value) {
  if (value?.format !== 'haiyue-ray-traversal-module-family' || value.version !== 1 || value.id !== 'ray-traversal') throw new Error('Invalid ray traversal module family identity.');
  if (value.accelerationAbiFingerprint !== 'fnv1a64:9fd4d41c38d10fa2') throw new Error('Ray traversal family drifted from frozen acceleration ABI v1.');
  if (value.entryPoint !== 'cs_main' || JSON.stringify(value.workgroupSize) !== '[64,1,1]' || value.stackCapacity !== 64) throw new Error('Ray traversal schedule/stack policy drifted.');
  if (!Array.isArray(value.bindings) || value.bindings.length !== 9 || value.bindings.some((binding, index) => binding.binding !== index)) throw new Error('Ray traversal bindings must be contiguous 0..8.');
}
