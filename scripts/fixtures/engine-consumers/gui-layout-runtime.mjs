import assert from 'node:assert/strict';
import {GuiRoot,GuiElement,GuiThemeResource,GuiNineSlice} from '@haiyue/engine/gui';
import {attachGuiLayout,createGuiContainer,GuiSplitPanel,GuiTabContainer} from '@haiyue/extensions/gui-layout';
const root=new GuiRoot(),first=createGuiContainer('column'),second=new GuiElement();
const split=new GuiSplitPanel({axis:'horizontal',ratio:.25,first,second,dividerSize:10});
const binding=attachGuiLayout(root,{measure:()=>({width:0,height:0,minWidth:0,minHeight:0})});
root.add(split.element);binding.setStyle(split.element,{width:410,height:200});root.layout(410,200);
assert.equal(split.firstPane.rect.width,100);assert.equal(split.secondPane.rect.width,300);
split.setRatio(.5);root.layout(410,200);assert.equal(split.firstPane.rect.width,200);
const a=new GuiElement(),b=new GuiElement();
const tabs=new GuiTabContainer({pages:[{id:'a',title:'A',content:a},{id:'b',title:'B',content:b}]});
assert.equal(tabs.activeId,'a');tabs.activate('b');assert.equal(tabs.activeId,'b');tabs.remove('b');assert.equal(tabs.activeId,'a');
const theme=new GuiThemeResource({controls:{GuiButton:{normal:{opacity:.75}}}});
assert.equal(theme.resolve('GuiButton',{hover:false,focus:false,pressed:false,disabled:false}).opacity,.75);
root.setThemeResource(theme);
const skin=root.add(new GuiNineSlice({source:null,sourceWidth:30,sourceHeight:30,cuts:[6,6,6,6],width:60,height:40}));
root.layout(410,200);assert.equal(skin.patches.length,9);
root.remove(skin);root.setThemeResource(null);theme.dispose();tabs.dispose();split.dispose();binding.dispose();root.destroy();
console.log('Packed GUI layout, panels, tabs and admitted skin constructors use the same Engine classes. No device/pixel acceptance claimed.');
