const root = resolve(fileURLToPath(new URL('../..', import.meta.url)));
const shaderLanguageEntry = resolve(root, 'shader-language/dist/index.js');
if (!existsSync(shaderLanguageEntry)) {
  execFileSync(process.platform === 'win32' ? 'npm.cmd' : 'npm', ['run', 'build', '-w', './shader-language'], { cwd: root, stdio: 'inherit' });
}
const { createPrecompiledShaderArtifactV2 } = await import(new URL('../../shader-language/dist/index.js', import.meta.url));
const familyPath = 'extensions/src/ray-tracing/renderer/shaders/path-tracing-family.json';
const tsOutput = 'extensions/src/ray-tracing/renderer/shaders/path-tracing-artifact.generated.ts';
const browserOutput = 'scripts/visual-regression/ray-path-tracing-artifact.generated.mjs';
const familySource = await readFile(resolve(root, familyPath), 'utf8');
const family = JSON.parse(familySource);
validateFamily(family);
const sources = new Map(await Promise.all(family.passes.map(async pass => [pass.source, await readFile(resolve(root, pass.source), 'utf8')])));
const canonicalHash = sha256(JSON.stringify(family));
const sourceHash = [...sources].map(([path, code]) => `${path}:${sha256(code)}`).join('\n');
const artifact = createPrecompiledShaderArtifactV2({
  compilerVersion: 'shader-language-ray-path-tracing-v1',
  source: { kind: 'module-family', path: familyPath, sha256: sha256(familySource) },
  canonicalHash,
  typedModuleHash: sha256(`${canonicalHash}\n${sourceHash}`),
  passes: family.passes.map(pass => {
    const code = sources.get(pass.source);
    if (code === undefined) throw new Error(`Missing authoritative WGSL source ${pass.source}.`);
    return ({
    id: pass.id,
    code,
    entryPoints: { compute: pass.entryPoint },
    bindGroups: [{
      logicalSpace: 'pass', logicalGroup: pass.logicalGroup, physicalGroup: pass.physicalGroup, owner: 'artifact',
      bindings: pass.bindings.map(binding => ({
        id: binding.id,
        binding: binding.binding,
        visibility: ['compute'],
        layout: bindingLayout(binding),
      })),
    }],
    uniformBlocks: pass.id === 'ray-path-tracing'
      ? [uniformBlock('pass.params', 128), uniformBlock('pass.lights', 512)]
      : [uniformBlock('tone.params', 128)],
    vertexBuffers: [], varyings: [], renderTargets: [],
    capabilities: ['compute', 'storage-buffer', 'sampled-texture', 'storage-texture'],
    passRequirements: ['webgpu', 'maxStorageBuffersPerShaderStage>=8', 'maxBindingsPerBindGroup>=15'],
    sourceMap: [{ sourceId: pass.id, sourceName: pass.source, generatedStartLine: 1, generatedEndLine: code.split(/\r?\n/u).length, sourceStartLine: 1, sourceStartColumn: 1 }],
  }); }),
});
const banner = '// Generated by scripts/visual-regression/verify-ray-path-tracing-shader.mjs. Do not edit.\n';
const literal = JSON.stringify(artifact, null, 2);
const expectedTs = `${banner}export const RAY_PATH_TRACING_SHADER_ARTIFACT = ${literal} as const;\n`;
const expectedBrowser = `${banner}export const RAY_PATH_TRACING_SHADER_ARTIFACT = ${literal};\n`;
if (process.argv.includes('--write')) {
  await writeFile(resolve(root, tsOutput), expectedTs, 'utf8');
  await writeFile(resolve(root, browserOutput), expectedBrowser, 'utf8');
} else {
  await verify(tsOutput, expectedTs); await verify(browserOutput, expectedBrowser);
}
console.log(`[ray-path-tracing:shader] ${process.argv.includes('--write') ? 'wrote' : 'verified'} Artifact V2 ${artifact.artifactHash.slice(0, 16)}, passes=${family.passes.length}, WGSL=${[...sources.values()].reduce((sum, code) => sum + code.length, 0)} bytes.`);

function bindingLayout(binding) {
  if (binding.kind === 'buffer') return { kind: 'buffer', bufferType: binding.bufferType, hasDynamicOffset: false, minBindingSize: binding.minBindingSize };
  if (binding.kind === 'texture') return { kind: 'texture', sampleType: binding.sampleType, viewDimension: binding.viewDimension, multisampled: binding.multisampled };
  if (binding.kind === 'sampler') return { kind: 'sampler', samplerType: binding.samplerType };
  if (binding.kind === 'storage-texture') return { kind: 'storage-texture', access: binding.access, format: binding.format, viewDimension: binding.viewDimension };
  throw new Error(`Unsupported ray path binding kind ${binding.kind}.`);
}
function uniformBlock(id, byteSize) {
  return { id, alignment: 16, byteSize, fields: [{ name: 'raw', type: `array<u32,${byteSize / 4}>`, offset: 0, size: byteSize, arrayStride: 4 }] };
}
function validateFamily(value) {
  if (value?.format !== 'haiyue-ray-path-tracing-module-family' || value.version !== 1 || value.id !== 'ray-path-tracing') throw new Error('Invalid ray path-tracing module family identity.');
  if (value.accelerationAbiFingerprint !== 'fnv1a64:9fd4d41c38d10fa2') throw new Error('Ray path-tracing family drifted from acceleration ABI v1.');
  if (JSON.stringify(value.workgroupSize) !== '[8,8,1]' || value.stackCapacity !== 64 || value.materialStride !== 128 || value.surfaceStride !== 128) throw new Error('Ray path-tracing schedule or packed ABI drifted.');
  if (!Array.isArray(value.passes) || value.passes.length !== 2) throw new Error('Ray path-tracing family requires trace and tone passes.');
  for (const pass of value.passes) {
    if (typeof pass.source !== 'string' || !pass.source.endsWith('.wgsl')) throw new Error(`${pass.id} requires an authoritative WGSL source.`);
    if (pass.physicalGroup !== 0) throw new Error(`${pass.id} must own group 0 in its independent shader module.`);
    if (pass.bindings.some((binding, index) => binding.binding !== index)) throw new Error(`${pass.id} bindings must be contiguous.`);
  }
  const trace = value.passes.find(pass => pass.id === 'ray-path-tracing');
  if (!trace || trace.bindings.length !== 15) throw new Error('Ray path-tracing pass requires its frozen 15 bindings.');
  if (trace.bindings.filter(binding => binding.kind === 'buffer' && binding.bufferType.includes('storage')).length !== 8) throw new Error('Ray path-tracing must fit the portable 8-storage-buffer limit.');
}
async function verify(path, expected) {
  let actual = null; try { actual = await readFile(resolve(root, path), 'utf8'); } catch { /* classified below */ }
  if (actual !== expected) throw new Error(`Stale ray path-tracing shader artifact: ${path}. Run this verifier with --write.`);
}
function sha256(value) { return createHash('sha256').update(value).digest('hex'); }
