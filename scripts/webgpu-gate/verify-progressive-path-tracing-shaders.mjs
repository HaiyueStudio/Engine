        bindGroups: [{ logicalSpace: 'pass', logicalGroup: pass.logicalGroup, physicalGroup: 0, owner: 'artifact',
          bindings: pass.bindings.map(binding => ({ id: binding.id, binding: binding.binding, visibility: ['compute'], layout: bindingLayout(binding) })) }],
