function validateFamily(family, definition) {
  if (family?.format !== definition.format || family.version !== 1 || !Array.isArray(family.passes) || family.passes.length !== 2) throw new Error(`Invalid module family ${definition.familyPath}.`);
  for (const pass of family.passes) {
    if (pass.physicalGroup !== 0 || typeof pass.source !== 'string' || pass.bindings.some((binding, index) => binding.binding !== index)) throw new Error(`${pass.id} binding ownership drifted.`);
  }
  if (family.format === 'haiyue-ray-progressive-module-family' && (family.sequenceId !== 'haiyue-halton23-cranley-pcg32-v1' || family.accumulationFormat !== 'rgba16float')) throw new Error('Progressive sampling contract drifted.');
}
function bindingLayout(binding) {
  if (binding.kind === 'buffer') return { kind: 'buffer', bufferType: binding.bufferType, hasDynamicOffset: false, minBindingSize: binding.minBindingSize };
  if (binding.kind === 'texture') return { kind: 'texture', sampleType: binding.sampleType, viewDimension: binding.viewDimension, multisampled: binding.multisampled };
  if (binding.kind === 'storage-texture') return { kind: 'storage-texture', access: binding.access, format: binding.format, viewDimension: binding.viewDimension };
  throw new Error(`Unsupported binding kind ${binding.kind}.`);
}
function uniformBlock(id, byteSize) { return { id, alignment: 16, byteSize, fields: [{ name: 'raw', type: `array<u32,${byteSize / 4}>`, offset: 0, size: byteSize, arrayStride: 4 }] }; }
async function verify(path, expected) { let actual = null; try { actual = await readFile(resolve(root, path), 'utf8'); } catch { /* classified below */ } if (actual !== expected) throw new Error(`Stale progressive shader artifact: ${path}. Run with --write.`); }
function sha256(value) { return createHash('sha256').update(value).digest('hex'); }
